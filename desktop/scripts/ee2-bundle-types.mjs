// The type declaration sync-ee2.mjs writes beside the generated EE2 bundle (vendor/bundle.d.cts).
// It declares, by hand, the part of the bundle that desktop/src/vendor/ee2-query/index.js uses, so the
// type checker reads this instead of the generated code. Edit it here, then regenerate the vendored
// copy and its manifest entry offline with `node scripts/sync-ee2.mjs --types-only`.
import fs from 'node:fs'
import path from 'node:path'

export const BUNDLE_TYPES = `// GENERATED by desktop/scripts/sync-ee2.mjs from desktop/scripts/ee2-bundle-types.mjs — do not edit here.
// The surface of the generated EE2 bundle (bundle.cjs, beside this file) that first-party code uses.
// index.js's require('./vendor/bundle.cjs') resolves to this declaration, so the type checker never
// reads the generated bundle. When index.js starts using more of the bundle, declare it in
// ee2-bundle-types.mjs and run "node scripts/sync-ee2.mjs --types-only".

export interface ItemInfo {
  name?: string
  refName?: string
}

export interface ItemModifier {
  info?: { type?: string; generation?: string; name?: string; tier?: number }
  stats?: Array<{ translation?: { string?: string }; stat?: { ref?: string } }>
}

export interface ParsedItem {
  name?: string
  baseType?: string
  category?: string
  rarity?: string
  itemLevel?: number
  isCorrupted?: boolean
  info?: ItemInfo
  newMods?: ItemModifier[]
}

export interface ParseResult {
  isOk(): boolean
  value: ParsedItem
  error: unknown
}

export interface SearchPreset {
  id: string
  stats: unknown[]
  filters: Record<string, unknown>
}

export interface PresetOptions {
  league?: string
  currency?: string
  listingType?: string
  [option: string]: unknown
}

export declare const ItemRarity: Readonly<Record<string, string>>
export declare const ItemCategory: Readonly<Record<string, string>>
export declare function init(language: string): Promise<void>
export declare function parseClipboard(raw: string): ParseResult
export declare function createPresets(item: ParsedItem, options: PresetOptions): { active: string; presets: SearchPreset[] }
export declare function apiToSatisfySearch(item: ParsedItem, stats: unknown[], filters: Record<string, unknown>): string
export declare function createTradeRequest(filters: Record<string, unknown>, stats: unknown[], item: ParsedItem): unknown
`

/** Write vendor/bundle.d.cts under the vendored port's directory. */
export function writeBundleTypes(vendorDir) {
  fs.writeFileSync(path.join(vendorDir, 'vendor', 'bundle.d.cts'), BUNDLE_TYPES)
}
